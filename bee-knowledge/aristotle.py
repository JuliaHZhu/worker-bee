def define(term: str, context: str, status: str = "draft") -> Path:
    """
    为一个无定义的新词写草案。
    输出: drafts/define-<term>.md
    """
    slug = re.sub(r"[^\w\-]+", "-", term.lower()).strip("-")
    content = f"""# define: {term}

- **Definition**: （待填写）基于以下上下文提炼：
  {context.replace(chr(10), chr(10) + '  ')}
- **Status**: {status}
- **Notes**:

---
> Generated by Aristotle.define at {datetime.now().isoformat()}
"""
    return draft_writer(f"define-{slug}.md", content)


def fork(term: str, usage_a: str, usage_b: str) -> Path:
    """
    发现同一词被用作两个意思时，写 fork 草案。
    输出: drafts/fork-<term>.md
    """
    slug = re.sub(r"[^\w\-]+", "-", term.lower()).strip("-")
    content = f"""# fork: {term}

发现该词存在两种实际用法，待解决。

## 用法 A
{usage_a}

## 用法 B
{usage_b}

## 建议
（待讨论：是拆成两个词，还是保留一词多义并标注场景？）

---
> Generated by Aristotle.fork at {datetime.now().isoformat()}
"""
    return draft_writer(f"fork-{slug}.md", content)


def resolve(fork_draft_name: str, conclusion: str) -> Path:
    """
    对一个 fork draft 给出解决结论。
    输出: drafts/resolve-<term>.md
    """
    # 从 fork draft 文件名提取 term
    base = fork_draft_name.replace("fork-", "").replace(".md", "")
    content = f"""# resolve: {base}

基于 fork 讨论结论：

{conclusion}

## 后续动作
- [ ] 人审阅后 merge 进 dict.md
- [ ] 如产生新术语，调用 define 补充

---
> Generated by Aristotle.resolve at {datetime.now().isoformat()}
"""
    return draft_writer(f"resolve-{base}.md", content)


def align(term: str, misusage: str, correct: str = "") -> Path:
    """
    发现某 Bee 用错词时，写对齐草案。
    输出: drafts/align-<term>.md
    """
    slug = re.sub(r"[^\w\-]+", "-", term.lower()).strip("-")
    content = f"""# align: {term}

## 误用实例
{misusage}

## 正确用法
{correct or "（待补充 dict.md 中的定义）"}

## 建议
（待讨论：是纠正用法，还是接受新用法并更新定义？）

---
> Generated by Aristotle.align at {datetime.now().isoformat()}
"""
    return draft_writer(f"align-{slug}.md", content)


def decide(topic: str, conclusion: str, decision_id: int = 0) -> Path:
    """
    对争议拍板后，记录决策草案。
    输出: drafts/decide-<NNNN>-<slug>.md
    """
    slug = re.sub(r"[^\w\-]+", "-", topic.lower()).strip("-")
    serial = f"{decision_id:04d}" if decision_id else "XXXX"
    content = f"""# Decision {serial}: {topic}

## 结论
{conclusion}

## 状态
- [ ] 人审阅后移入 decisions/{serial}-{slug}.md

---
> Generated by Aristotle.decide at {datetime.now().isoformat()}
"""
    return draft_writer(f"decide-{serial}-{slug}.md", content)


def grill(term: str, question: str) -> Path:
    """
    对一个术语定义进行追问，暴露不稳之处。
    输出: drafts/grill-<term>.md
    """
    slug = re.sub(r"[^\w\-]+", "-", term.lower()).strip("-")
    content = f"""# grill: {term}

## 追问
{question}

## 待回答
（待讨论：这个追问是否暴露了定义的漏洞？）

---
> Generated by Aristotle.grill at {datetime.now().isoformat()}
"""
    return draft_writer(f"grill-{slug}.md", content)


def relate(term_a: str, term_b: str, relation: str) -> str:
    """
    在 define draft 的 Notes 中标注两术语关系。
    由于只能写 drafts/，这里返回一段应追加到 Notes 的文本，
    由调用方自行写入对应的 define draft。
    """
    return f"See also: {term_b} — {relation}"


