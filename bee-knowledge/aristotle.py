"""
Aristotle — 10 skills × 5 tools × 1 rule.

铁律：AI 不能写 dict.md 和 decisions/。所有产出进 drafts/，等人 merge。
"""

import os
import re
import subprocess
from datetime import datetime
from pathlib import Path

# ── 常量 ──────────────────────────────────────────────────────────
BASE_DIR = Path(__file__).parent
DICT_PATH = BASE_DIR / "dict.md"
DECISIONS_DIR = BASE_DIR / "decisions"
DRAFTS_DIR = BASE_DIR / "drafts"
BLOCKED = {"dict.md", "decisions/"}          # 唯一铁律

# 确保 drafts/ 存在
DRAFTS_DIR.mkdir(exist_ok=True)


def _guard(path: str) -> None:
    """draft-writer 的安全检查。"""
    for p in BLOCKED:
        if p in path:
            raise PermissionError(f"AI 不能写 {p} — 只能写 drafts/")


# ═══════════════════════════════════════════════════════════════════
# Tools（5 个）— Skills 不直接碰文件系统，通过 Tools 操作
# ═══════════════════════════════════════════════════════════════════

def dict_reader() -> str:
    """读取 dict.md，返回全文。"""
    if not DICT_PATH.exists():
        return ""
    return DICT_PATH.read_text(encoding="utf-8")


def decision_reader() -> list[tuple[str, str]]:
    """读取 decisions/ 下所有 .md，返回 [(filename, content), ...]。"""
    files = sorted(DECISIONS_DIR.glob("*.md")) if DECISIONS_DIR.exists() else []
    return [(f.name, f.read_text(encoding="utf-8")) for f in files]


def draft_writer(filename: str, content: str) -> Path:
    """
    写入 drafts/*.md。唯一可写入口。
    文件名不需要带路径，自动放在 drafts/ 下。
    """
    if "/" in filename or "\\" in filename:
        raise ValueError("filename 不能包含路径分隔符")
    path = DRAFTS_DIR / filename
    _guard(str(path.relative_to(BASE_DIR)))
    path.write_text(content, encoding="utf-8")
    return path


def log_scanner(text: str, terms: list[str]) -> dict[str, list[str]]:
    """
    在文本中扫描术语使用实例。
    返回 {term: [包含该 term 的行, ...]}。
    """
    lines = text.splitlines()
    result = {}
    for term in terms:
        hits = [line for line in lines if re.search(rf"\b{re.escape(term)}\b", line, re.I)]
        if hits:
            result[term] = hits
    return result


def git_commit(message: str) -> str:
    """git add + git commit drafts/ 变更。"""
    try:
        subprocess.run(["git", "add", str(DRAFTS_DIR)], cwd=BASE_DIR, check=True)
        subprocess.run(
            ["git", "commit", "-m", message],
            cwd=BASE_DIR, check=True, capture_output=True, text=True,
        )
        return "committed"
    except subprocess.CalledProcessError as e:
        # 可能没有变更需要提交
        return f"nothing to commit or error: {e.stderr.strip()}"


