if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: python aristotle.py <skill> [args...]")
        print("Skills:", " ".join([
            "define", "fork", "resolve", "align", "decide", "grill", "relate",
            "drift_watch", "ammo_prep", "audit_debt"
        ]))
        sys.exit(1)

    skill = sys.argv[1]
    args = sys.argv[2:]

    try:
        result = globals()[skill](*args)
        print(result)
        # 自动 commit
        print(git_commit(f"Aristotle: {skill}"))
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
