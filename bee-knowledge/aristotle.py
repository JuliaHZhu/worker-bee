def drift_watch(text: str) -> Path:
    """
    扫描日志/对话，发现术语漂移。
    输出: drafts/drift-YYYY-MM-DD.md
    """
    # 先读 dict 提取术语列表
    dict_text = dict_reader()
    terms = re.findall(r"^## (.+)$", dict_text, re.M)
    hits = log_scanner(text, terms)

    date = datetime.now().strftime("%Y-%m-%d")
    lines = [f"# drift-watch: {date}\n", f"扫描到 {len(hits)} 个术语出现：\n"]
    for term, ctx in hits.items():
        lines.append(f"\n### {term}\n")
        for c in ctx[:5]:          # 最多列 5 条
            lines.append(f"- {c.strip()}")
    lines.append(f"\n---\n> Generated by Aristotle.drift_watch at {datetime.now().isoformat()}\n")

    return draft_writer(f"drift-{date}.md", "\n".join(lines))


def ammo_prep(topic: str, requester: str = "") -> Path:
    """
    为其他 Bee 准备术语弹药包。
    输出: drafts/ammo-<topic>.md（标 [DRAFT]）
    """
    slug = re.sub(r"[^\w\-]+", "-", topic.lower()).strip("-")
    dict_text = dict_reader()
    # 简单提取相关段落：包含 topic 的条目
    sections = []
    for block in dict_text.split("\n---\n"):
        if topic.lower() in block.lower():
            sections.append(block.strip())

    sep = "\n\n"
    content = f"""# [DRAFT] ammo: {topic}

> 请求方: {requester or "unknown"}
> 状态: DRAFT — 人审阅后删除 [DRAFT] 标记或丢弃

## 相关定义
{sep.join(sections) or "（未在 dict.md 中找到直接匹配，请人工补充）"}

---
> Generated by Aristotle.ammo_prep at {datetime.now().isoformat()}
"""
    return draft_writer(f"ammo-{slug}.md", content)


def audit_debt() -> Path:
    """
    批次收尾时清算草稿债务。
    输出: drafts/audit-YYYY-MM-DD.md
    """
    date = datetime.now().strftime("%Y-%m-%d")
    drafts = sorted(DRAFTS_DIR.glob("*.md"))

    lines = [f"# audit-debt: {date}\n", f"当前 drafts/ 共有 {len(drafts)} 个文件：\n"]
    for d in drafts:
        lines.append(f"- `{d.name}`")
    lines.append("\n## 建议")
    lines.append("- 标 `[DRAFT]` 的 ammo 文件：用后即焚或定期清理")
    lines.append("- define/fork/resolve/decide：等人 merge 后删除")
    lines.append(f"\n---\n> Generated by Aristotle.audit_debt at {datetime.now().isoformat()}\n")

    return draft_writer(f"audit-{date}.md", "\n".join(lines))


